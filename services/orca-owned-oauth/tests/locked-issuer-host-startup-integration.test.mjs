// Stage 23: actual oidc-provider boot from ephemeral local secret files.
// NO production keys, network calls, database writes, or listeners.
import test from 'node:test';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {
  mkdtempSync,mkdirSync,writeFileSync,readFileSync,rmSync,
  chmodSync,linkSync,symlinkSync
} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {generateKeyPairSync,randomBytes} from 'node:crypto';
import Provider from 'oidc-provider';
import {createStage22LockedIssuerHostStartup} from '../locked-issuer-host-startup.mjs';

const REJECT=/stage22_locked_secret_startup_rejected/;
const project='vbziibatnejoswsdggga';
const env=Object.freeze({
  ORCA_STAGE22_LOCKED_ACK:'OFFLINE_ASSEMBLY_ONLY',
  ORCA_OWNED_ISSUER_ENABLED:'false',
  ORCA_MCP_ENABLED:'false',
  ORCA_DB_PROJECT_REF:project,
  ORCA_SUPABASE_URL:'https://'+project+'.supabase.co',
  ORCA_DB_MODE:'direct',
  ORCA_DB_HOST:'db.'+project+'.supabase.co',
  ORCA_DB_LOGIN_USER:'orca_owned_issuer_login',
  ORCA_ISSUER_ORIGIN:'https://issuer.orca.example.invalid',
  ORCA_MCP_RESOURCE:'https://mcp.orca.example.invalid/mcp',
  ORCA_OAUTH_CLIENT_ID:'stage23-explicit-test-client',
  ORCA_OAUTH_REDIRECT_URI:'https://callback.example.invalid/authorized'
});
const key=()=>randomBytes(32).toString('base64url');

function createFixture(){
  const root=mkdtempSync(join(tmpdir(),'orca-issuer-stage23-'));
  const directory=join(root,'secrets');
  mkdirSync(directory,{mode:0o700});
  const save=(filename,contents)=>{
    const path=join(directory,filename);
    writeFileSync(path,typeof contents==='string'?contents:JSON.stringify(contents),
      {mode:0o600});
    return path;
  };
  const {privateKey}=generateKeyPairSync('ec',{namedCurve:'P-256'});
  save('signing-jwk.json',{
    ...privateKey.export({format:'jwk'}),kid:'stage23-signing-key',
    alg:'ES256',use:'sig'
  });
  save('provider-cookie-keys.json',[key(),key()]);
  save('provider-keyring.json',{currentKeyId:'stage23-provider-001',
    keys:{'stage23-provider-001':key()}});
  save('browser-session-keyring.json',{keys:[
    {id:'stage23-browser-001',key:key()}
  ]});
  save('issuer-db-password.txt',randomBytes(48).toString('base64url'));
  save('supabase-publishable-key.txt','sb_publishable_'+randomBytes(32).toString('base64url'));

  // Ephemeral test-only CA, generated by Ubuntu's OpenSSL at test time.
  // Never use this certificate or key outside CI.
  const caKey=join(root,'ephemeral-ca.key');
  const caCrt=join(root,'ephemeral-ca.crt');
  execFileSync('openssl',[
    'req','-x509','-newkey','rsa:2048','-nodes','-days','2',
    '-subj','/CN=ORCA Stage23 Ephemeral CA',
    '-keyout',caKey,'-out',caCrt
  ],{stdio:'ignore'});
  save('postgres-ca.pem',readFileSync(caCrt,'utf8'));
  return {root,directory,save};
}
function response(){
  return {status:0,body:'',headersSent:false,writableEnded:false,
    writeHead(status){this.status=status;this.headersSent=true;},
    end(body){this.body=String(body);this.writableEnded=true;}};
}
test('protected mount assembles real OAuth provider; every route stays offline',async()=>{
  const fixture=createFixture();
  let sql=0,requests=0,constructors=0;
  class NeverConnect {
    constructor(){constructors++;throw Error('NO_REAL_DB_ALLOWED');}
  }
  const fetchImpl=async()=>{requests++;throw Error('NO_REAL_HTTP_ALLOWED');};
  try{
    const issuer=createStage22LockedIssuerHostStartup({
      env,secretDirectory:fixture.directory,
      ProviderClass:Provider,ClientClass:NeverConnect,fetchImpl
    });
    assert.equal(issuer.mode,'locked-staging');
    assert.equal(issuer.publicAuthorizationEnabled,false);
    assert.equal(issuer.issuer,env.ORCA_ISSUER_ORIGIN);
    assert.equal(issuer.resource,env.ORCA_MCP_RESOURCE);
    assert.equal(Object.isFrozen(issuer),true);
    for(const name of ['provider','callback','signingKey','privateSigningJwk',
      'verifiedIssuerConnector','grantRegistry'])
      assert.equal(Object.hasOwn(issuer,name),false,name+' exposed');
    for(const path of [
      '/auth','/token','/.well-known/oauth-authorization-server',
      '/interaction/abcdefgh/approve','/interaction/abcdefgh',
      '/session/bootstrap','/healthz'
    ]){
      const res=response();
      await issuer.handle({url:path,method:'GET',headers:{}},res);
      assert.equal(res.status,503,path);
      assert.ok(!res.body.includes('PRIVATE KEY'));
      assert.ok(!res.body.includes('issuer-db-password'));
    }
    assert.equal(sql,0);
    assert.equal(requests,0,'assembly and locked routes never contact Supabase');
    assert.equal(constructors,0,'assembly and locked routes never open PostgreSQL');
  }finally{rmSync(fixture.root,{recursive:true,force:true});}
});

test('valid config rejects missing key, invalid signing pair and cross-purpose reuse',()=>{
  const fixture=createFixture();
  try{
    const invoke=()=>createStage22LockedIssuerHostStartup({
      env,secretDirectory:fixture.directory,
      ProviderClass:Provider,ClientClass:class {},
      fetchImpl:async()=>{throw Error('unexpected_http');}
    });
    const badJwk={...generateKeyPairSync('ec',{namedCurve:'P-256'})
      .privateKey.export({format:'jwk'}),kid:'stage23-signing-key'};
    badJwk.x='A'.repeat(43);
    fixture.save('signing-jwk.json',badJwk);
    assert.throws(invoke,REJECT);
    const {privateKey}=generateKeyPairSync('ec',{namedCurve:'P-256'});
    fixture.save('signing-jwk.json',
      {...privateKey.export({format:'jwk'}),kid:'stage23-signing-key'});
    const duplicate=key();
    fixture.save('provider-cookie-keys.json',[duplicate,key()]);
    fixture.save('provider-keyring.json',{currentKeyId:'stage23-provider-001',
      keys:{'stage23-provider-001':duplicate}});
    assert.throws(invoke,REJECT);
    fixture.save('provider-keyring.json',{currentKeyId:'stage23-provider-001',
      keys:{'stage23-provider-001':key()}});
    chmodSync(join(fixture.directory,'postgres-ca.pem'),0o644);
    assert.throws(invoke,REJECT);
  }finally{rmSync(fixture.root,{recursive:true,force:true});}
});

test('secret files must not be symlinks, hardlinks or executable',()=>{
  const fixture=createFixture();
  const invoke=()=>createStage22LockedIssuerHostStartup({
    env,secretDirectory:fixture.directory,
    ProviderClass:Provider,ClientClass:class {},fetchImpl:async()=>{}
  });
  try{
    const pass=join(fixture.directory,'issuer-db-password.txt');
    const hardlink=join(fixture.directory,'secret-copy');
    linkSync(pass,hardlink);
    assert.throws(invoke,REJECT);
    rmSync(hardlink);
    const symlink=join(fixture.directory,'postgres-ca.pem');
    const original=join(fixture.root,'ca-copy.pem');
    const caContent=readFileSync(symlink);
    rmSync(symlink);
    writeFileSync(original,caContent,{mode:0o600});
    symlinkSync(original,symlink);
    assert.throws(invoke,REJECT);
  }finally{rmSync(fixture.root,{recursive:true,force:true});}
});
